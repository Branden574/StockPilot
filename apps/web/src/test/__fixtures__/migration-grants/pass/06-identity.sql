-- Identity columns: Postgres draws their values without checking the
-- inserting role's privileges on the identity sequence, so the table's own
-- decisions are enough and no sequence decision is asked for.
create table public.events (
  id bigint generated always as identity primary key,
  seq integer generated by default as identity,
  note text
);
revoke all on public.events from anon, authenticated, service_role;
grant select, insert on public.events to authenticated, service_role;

create table public.audit_marks (note text);
alter table public.audit_marks add column id bigint generated always as identity;
revoke all on public.audit_marks from anon, authenticated, service_role;
grant select, insert on public.audit_marks to authenticated, service_role;
