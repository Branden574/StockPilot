import { PlanningService, DEFAULT_PLANNING_PARAMS, PLANNING_MAX_ITEMS } from './planning';

/** Module set that INCLUDES planning (an org that opted in). */
const withPlanning = () => new Set<ModuleId>([...DEFAULT_MODULE_IDS, 'planning']);

/** Build a velocity snapshot for a given item id (bulk-velocity result). */
function velocity(
  itemId: string,
  opts: { unitsPerDay?: number; daysOfStock?: number | null; qtyOnHand?: number } = {},
) {
  return {
    itemId,
    unitsOutPerDay: opts.unitsPerDay ?? 0,
    unitsOutTotal: 0,
    windowDays: 90,
    quantityOnHand: opts.qtyOnHand ?? 0,
    daysOfStockRemaining: opts.daysOfStock ?? null,
    projectedRunoutAt: null,
  };
}

/** Build a forecast (ReorderSuggestion) result for a given velocity snapshot. */
function forecast(
  v: ReturnType<typeof velocity>,
  opts: { suggestedReorderPoint?: number; suggestedReorderQty?: number; currentReorderPoint?: number } = {},
) {
  return {
    itemId: v.itemId,
    suggestedReorderPoint: opts.suggestedReorderPoint ?? 0,
    suggestedReorderQty: opts.suggestedReorderQty ?? 0,
    currentReorderPoint: opts.currentReorderPoint ?? 0,
    currentReorderQty: 0,
    leadTimeDays: 14,
    safetyMultiplier: 1.5,
    rationale: 'test',
    velocity: v,
  };
}

