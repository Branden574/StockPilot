describe('PlanningService.getReorderSuggestions', () => {
  it('composes suggestions from forecasting and sorts by urgency (lowest cover first)', async () => {
    const created = '2020-01-01T00:00:00.000Z';
    const items = [
      { id: 'item-a', sku: 'A', name: 'Alpha', quantity_on_hand: 5, reorder_point: 2, reorder_quantity: 0, unit_cost: 3, supplier_id: 'sup-1', created_at: created },
      { id: 'item-b', sku: 'B', name: 'Bravo', quantity_on_hand: 20, reorder_point: 4, reorder_quantity: 0, unit_cost: 1, supplier_id: null, created_at: created },
      { id: 'item-c', sku: 'C', name: 'Charlie', quantity_on_hand: 0, reorder_point: 0, reorder_quantity: 0, unit_cost: 2, supplier_id: 'sup-1', created_at: created },
    ];
    const stub = makeSupabaseStub({
      'organization_modules.select': { data: { settings: {} }, error: null },
      'inventory_items.select': { data: items, error: null },
      'suppliers.select': { data: [{ id: 'sup-1', name: 'Supplier One' }], error: null },
    });

    // item-a: 10 days cover. item-b: 40 days cover. item-c: no movement (null).
    const velA = velocity('item-a', { unitsPerDay: 0.5, daysOfStock: 10, qtyOnHand: 5 });
    const velB = velocity('item-b', { unitsPerDay: 0.5, daysOfStock: 40, qtyOnHand: 20 });
    const velC = velocity('item-c', { unitsPerDay: 0, daysOfStock: null, qtyOnHand: 0 });
    getBulkItemVelocities.mockResolvedValue(
      new Map([
        ['item-a', velA],
        ['item-b', velB],
        ['item-c', velC],
      ]),
    );
    computeReorderSuggestion.mockImplementation((v) => {
      if (v.itemId === 'item-a') return forecast(velA, { suggestedReorderPoint: 11 });
      if (v.itemId === 'item-b') return forecast(velB, { suggestedReorderPoint: 11 });
      return forecast(velC, { suggestedReorderPoint: 0 });
    });

    const svc = new PlanningService(makeServiceContext(stub.client, { enabledModules: withPlanning() }));
    const { suggestions: result, truncated } = await svc.getReorderSuggestions();
    expect(truncated).toBe(false);

    // Order: lowest cover first -> a (10), b (40), then non-moving c (null).
    expect(result.map((r) => r.itemId)).toEqual(['item-a', 'item-b', 'item-c']);

    // Composed fields are carried through from forecasting + the item row.
    const a = result[0]!;
    expect(a.sku).toBe('A');
    expect(a.name).toBe('Alpha');
    expect(a.supplierName).toBe('Supplier One');
    expect(a.unitsPerDay).toBe(0.5);
    expect(a.daysOfStockRemaining).toBe(10);
    expect(a.suggestedReorderPoint).toBe(11);
    expect(a.unitCost).toBe(3);

    // No-supplier item carries a null supplierName.
    expect(result.find((r) => r.itemId === 'item-b')?.supplierName).toBeNull();

    // Velocity was computed in ONE bulk call (no per-item fan-out).
    expect(getBulkItemVelocities).toHaveBeenCalledTimes(1);
    expect(getBulkItemVelocities.mock.calls[0]![3]).toBe(DEFAULT_PLANNING_PARAMS.velocityWindowDays);
    // The reorder formula was applied per item with the resolved (default) params.
    expect(computeReorderSuggestion).toHaveBeenCalledTimes(3);
    expect(computeReorderSuggestion.mock.calls[0]![3]).toEqual({
      leadTimeDays: DEFAULT_PLANNING_PARAMS.leadTimeDays,
      safetyMultiplier: DEFAULT_PLANNING_PARAMS.safetyMultiplier,
    });
  });

  it('returns [] when there are no candidate items', async () => {
    const stub = makeSupabaseStub({
      'organization_modules.select': { data: { settings: {} }, error: null },
      'inventory_items.select': { data: [], error: null },
    });
    const svc = new PlanningService(makeServiceContext(stub.client, { enabledModules: withPlanning() }));
    await expect(svc.getReorderSuggestions()).resolves.toEqual({ suggestions: [], truncated: false });
    expect(getBulkItemVelocities).not.toHaveBeenCalled();
  });

  it('paginates the candidate fetch past the 1000-row PostgREST cap', async () => {
    // The Data API clamps any single response to max_rows=1000. A candidate set
    // of 2300 items must therefore be assembled across .range() pages — the old
    // .limit(5000) silently returned only the first 1000, so items past 1000 got
    // NO reorder suggestion. Hand the stub successive 1000-row pages.
    const PAGE = 1000;
    const TOTAL = 2300;
    let page = 0;
    const stub = makeSupabaseStub({
      'organization_modules.select': { data: { settings: {} }, error: null },
      'inventory_items.select': () => {
        const start = page * PAGE;
        const rows: Record<string, unknown>[] = [];
        for (let i = start; i < Math.min(start + PAGE, TOTAL); i += 1) {
          rows.push({
            id: `item-${i.toString().padStart(6, '0')}`,
            sku: `S${i}`,
            name: `Item ${i}`,
            quantity_on_hand: 1,
            reorder_point: 5,
            reorder_quantity: 0,
            unit_cost: 1,
            supplier_id: null,
            created_at: '2020-01-01T00:00:00.000Z',
          });
        }
        page += 1;
        return { data: rows, error: null };
      },
      'suppliers.select': { data: [], error: null },
    });
    // Velocity + forecast: every item is a flat passthrough; the assertion is
    // about completeness of the candidate set, not the math.
    getBulkItemVelocities.mockImplementation(async (_s, _o, items: Array<{ id: string }>) => {
      const m = new Map<string, ReturnType<typeof velocity>>();
      for (const it of items) m.set(it.id, velocity(it.id, { unitsPerDay: 1, daysOfStock: 1 }));
      return m;
    });
    computeReorderSuggestion.mockImplementation((v: ReturnType<typeof velocity>) =>
      forecast(v, { suggestedReorderPoint: 5 }),
    );

    const svc = new PlanningService(makeServiceContext(stub.client, { enabledModules: withPlanning() }));
    const { suggestions: result, truncated } = await svc.getReorderSuggestions();

    // All 2300 candidates surfaced — not just the first 1000.
    expect(result).toHaveLength(TOTAL);
    expect(truncated).toBe(false);
    expect(result.some((r) => r.itemId === 'item-002299')).toBe(true);
    // At least three .range() pages were issued (1000 + 1000 + 300).
    const ranges = stub.chainArgsAll.get('inventory_items.select') ?? [];
    expect(ranges.length).toBeGreaterThanOrEqual(3);
  });
});

