import * as React from 'react';

import { cn } from '@/lib/utils';

/**
 * Card (DESIGN-SPEC 6.7): the elevated surface, a 1 px hairline, radius 8 and no
 * shadow (cards are flat in the redesign). Sections pad 18 px, the reference
 * card rhythm.
 */
