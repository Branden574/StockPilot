/**
 * Policy sign-off: the hash of the exact words a member was shown.
 *
 * policyTextHash(title, body) is SHA-256, written as 64 lower-case hex
 * digits, of the UTF-8 bytes of
 *
 *     title + "\n\n" + body
 *
 * where title and body are each already in normal form (policy-text.ts:
 * normalizePolicyTitle, normalizePolicyBody). A title never holds a line
 * feed, so the two parts cannot be confused. The database computes the same
 * value for every stored version (migration 0482: org_policy_versions
 * text_hash, checked by org_policy_versions_text_hash) as
 *
 *     encode(sha256(convert_to(title || E'\n\n' || body, 'UTF8')), 'hex')
 *
 * and every acknowledgement stores the hash of the version it was given for.
 * The website and the phone send back the hash that came with the text they
 * showed; they may recompute it here first and refuse to offer the button if
 * the two differ.
 *
 * The SHA-256 below is written out (FIPS 180-4) so the phone needs no native
 * module and no Web Crypto; policy-hash.test.ts checks it against Node's
 * crypto and against the published test vectors.
 *
 * PURE: no I/O, no platform imports.
 */

